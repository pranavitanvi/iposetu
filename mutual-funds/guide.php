<h2 style="font-size: 24px; font-weight: 800; color: #0f172a; margin-bottom: 16px;">1. What is a Mutual Fund?</h2>
<p style="font-size: 16px; color: #475569; line-height: 1.8; margin-bottom: 24px;">A mutual fund is a financial vehicle that pools money collected from many investors to invest in securities like stocks, bonds, money market instruments, and other assets. They are operated by professional money managers.</p>
