<h2 style="font-size: 24px; font-weight: 800; color: #0f172a; margin-bottom: 16px;">2. Types of Mutual Funds</h2>
<p style="font-size: 16px; color: #475569; line-height: 1.8; margin-bottom: 24px;">Mutual funds are primarily divided into three categories based on where they invest your money:</p>
<ul style="font-size: 16px; color: #475569; line-height: 1.8; margin-left: 20px;">
<li><strong>Equity Funds:</strong> Invest in stocks. High risk, high return.</li>
<li><strong>Debt Funds:</strong> Invest in government bonds and corporate debt. Lower risk, stable return.</li>
<li><strong>Hybrid Funds:</strong> A mix of both equity and debt to balance risk and return.</li>
</ul>
</section>
<section id="section-3" style="margin-bottom: 48px; scroll-margin-top: 100px;">
<h2 style="font-size: 24px; font-weight: 800; color: #0f172a; margin-bottom: 16px;">3. SIP vs Lumpsum</h2>
<p style="font-size: 16px; color: #475569; line-height: 1.8; margin-bottom: 24px;">You can invest in mutual funds in two ways:</p>
<p style="font-size: 16px; color: #475569; line-height: 1.8; margin-bottom: 24px;"><strong>SIP (Systematic Investment Plan):</strong> Investing a fixed amount regularly (e.g., monthly). This helps average out market volatility.</p>
<p style="font-size: 16px; color: #475569; line-height: 1.8; margin-bottom: 24px;"><strong>Lumpsum:</strong> Investing a large amount all at once. Best when you have surplus cash and the market is undervalued.</p>
</section>
<section id="section-4" style="margin-bottom: 48px; scroll-margin-top: 100px;">
<h2 style="font-size: 24px; font-weight: 800; color: #0f172a; margin-bottom: 16px;">4. Taxation Rules</h2>
<p style="font-size: 16px; color: #475569; line-height: 1.8; margin-bottom: 24px;">Mutual funds are taxed based on the type of fund and how long you hold the investment. Equity funds held for more than 1 year incur Long Term Capital Gains (LTCG) tax of 12.5% on profits over ₹1.25 Lakh. If sold before 1 year, Short Term Capital Gains (STCG) tax of 20% applies.</p>
</section>
