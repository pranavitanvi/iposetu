        <h2>1. What is Financial Risk?</h2>
        <p>In finance, risk refers to the degree of uncertainty and/or potential financial loss inherent in an investment decision. It is the possibility that your actual return will differ from your expected return, including the possibility of losing some or all of your original investment.</p>

        <h2>2. Types of Investment Risks</h2>
        <ul>
            <li><strong>Market Risk (Systematic Risk):</strong> The risk that the overall market will decline due to macro factors like recessions, political turmoil, or pandemics. You cannot diversify away market risk.</li>
            <li><strong>Specific Risk (Unsystematic Risk):</strong> Risks tied to a specific company or industry, such as a CEO scandal or regulatory changes. You can eliminate this by diversifying your portfolio.</li>
            <li><strong>Inflation Risk:</strong> The risk that the return on your investment will not keep pace with inflation, eroding your purchasing power. Fixed deposits often suffer from this.</li>
            <li><strong>Liquidity Risk:</strong> The risk that you will not be able to sell your investment quickly without taking a significant loss (common in real estate or penny stocks).</li>
        </ul>

        <h2>3. Risk Tolerance vs. Risk Capacity</h2>
        <p>Understanding the difference between these two is critical for asset allocation:</p>
        <p><strong>Risk Tolerance:</strong> This is psychological. It is your emotional comfort with volatility. If your portfolio drops 30% and you panic and sell, you have low risk tolerance, regardless of your wealth.</p>
        <p><strong>Risk Capacity:</strong> This is financial. It is your mathematical ability to endure a loss without it affecting your standard of living or goals. A 25-year-old with a stable job has high risk capacity; a 65-year-old retiree living off their portfolio has low risk capacity.</p>

