        <h2>4. Managing and Mitigating Risk</h2>
        <p>Risk cannot be entirely avoided if you want returns, but it can be managed:</p>
        <ul>
            <li><strong>Diversification:</strong> "Don't put all your eggs in one basket." Spread investments across asset classes (Equity, Debt, Gold), geographies, and sectors.</li>
            <li><strong>Asset Allocation:</strong> Balance your portfolio according to your age and goals. A common rule of thumb is '100 minus your age' should be your equity percentage.</li>
            <li><strong>Long-Term Horizon:</strong> Time heals market wounds. The longer you stay invested in high-quality equities, the lower the probability of losing money.</li>
            <li><strong>Emergency Fund:</strong> Always maintain 6-12 months of living expenses in a liquid savings account to avoid selling investments during a market crash.</li>
        </ul>
    
