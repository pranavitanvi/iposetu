        <h2>Why Bidding at 'Cut-Off Price' Is Crucial</h2>
        <p>In book-built IPOs, a price band (e.g. ₹475 – ₹500) is specified. When an issue is oversubscribed, the final discovered price is almost always the upper cap (₹500). If you place a bid at ₹480 or ₹490, your bid is automatically rejected as invalid. Checking the <strong>'Cut-off Price'</strong> box ensures that your bid automatically tracks whatever price the company finalizes.</p>

