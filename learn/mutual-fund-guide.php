        <h2>4. Understanding NAV and Expense Ratio</h2>
        <p><strong>NAV (Net Asset Value):</strong> The price of one unit of the mutual fund. It is calculated daily by dividing the total value of all assets in the portfolio minus liabilities, by the total number of outstanding units.</p>
        <p><strong>Expense Ratio:</strong> The annual fee charged by the AMC to manage your money, covering fund manager salaries, marketing, and administration. For example, an expense ratio of 1% means you pay ₹10 annually for every ₹1,000 invested. Lower expense ratios are crucial for maximizing long-term compounding.</p>

        <h2>5. Direct vs. Regular Plans</h2>
        <p>Always opt for <strong>Direct Plans</strong> when investing in mutual funds. Direct plans are bought directly from the AMC (or via platforms like Zerodha Coin, Groww), bypassing distributors and brokers. This eliminates commissions, resulting in a significantly lower expense ratio and much higher returns over the long term compared to Regular plans.</p>
    
