        <h2>1. What is a Mutual Fund?</h2>
        <p>A mutual fund is a financial vehicle that pools money collected from many investors to invest in securities like stocks, bonds, money market instruments, and other assets. They are operated by professional money managers (Asset Management Companies - AMCs), who allocate the fund's assets and attempt to produce capital gains or income for the investors.</p>

        <h2>2. Active vs. Passive Mutual Funds</h2>
        <p><strong>Active Funds:</strong> A fund manager conducts extensive research and buys/sells specific stocks with the goal of beating a benchmark index (like the NIFTY 50). Because of the active management, these funds charge a higher Expense Ratio.</p>
        <p><strong>Passive Funds (Index Funds):</strong> These funds simply replicate a market index, buying the exact same stocks in the exact same proportions. There is no active stock picking. They aim to match the market return, not beat it, and thus have very low expense ratios.</p>

        <h2>3. Types of Mutual Funds</h2>
        <ul>
            <li><strong>Equity Funds:</strong> Invest primarily in stocks. High risk, high reward. Ideal for long-term goals (5+ years). Subcategories include Large Cap, Mid Cap, Small Cap, and Sectoral funds.</li>
            <li><strong>Debt Funds:</strong> Invest in fixed-income securities like government bonds and corporate debentures. Lower risk, steady returns. Ideal for short to medium-term goals.</li>
            <li><strong>Hybrid Funds:</strong> Invest in a mix of both equity and debt, balancing risk and reward.</li>
            <li><strong>ELSS (Equity Linked Savings Scheme):</strong> Tax-saving mutual funds under Section 80C. They have a mandatory lock-in period of 3 years.</li>
        </ul>

