                        Understanding EBITDA &amp; Margins
                    </h4>
<p><strong>EBITDA (Earnings Before Interest, Taxes, Depreciation, and Amortization)</strong> is a measure of a company's overall financial performance and is used as an alternative to net income in some circumstances. It focuses purely on operational profitability by stripping away non-operating expenses.</p>
<p><strong>EBITDA Margin</strong> is calculated as <code>(EBITDA / Total Revenue) � 100</code>. It shows how much operating cash is generated for each rupee of revenue earned.</p>
<p><strong>Margin Expansion vs Contraction:</strong> If revenue grows by 10% but EBITDA grows by 15%, the company is experiencing <em>Margin Expansion</em>�it is becoming more efficient at converting sales into profit. If EBITDA only grows by 5%, it's experiencing <em>Margin Contraction</em> (costs are rising faster than sales).</p>
</div>
