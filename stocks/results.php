                        Profit vs Revenue Growth
                    </h4>
<p>Why can PAT (Profit After Tax) growth differ wildly from Revenue growth?</p>
<ul style="padding-left: 20px; font-size:14px; color:#475569; display:flex; flex-direction:column; gap:8px;">
<li><strong>Raw Material Costs:</strong> Sudden spikes in input costs eat into profits even if sales volume is high.</li>
<li><strong>Interest Costs:</strong> A heavily indebted company might lose operating profit to rising interest rates.</li>
<li><strong>Exceptional Items:</strong> One-time asset sales or legal settlements can artificially inflate or deflate PAT for a single quarter.</li>
</ul>
