        <script>
        function filterFAQs(event, category) {
            event.preventDefault();
            
            // Update active link styling
            const links = document.querySelectorAll('.cat-link');
            links.forEach(link => {
                link.style.color = '#475569';
            });
            event.target.style.color = '#2563eb';
            
            // Filter FAQ items
            const faqs = document.querySelectorAll('.faq-item');
            faqs.forEach(faq => {
                if (category === 'all' || faq.dataset.category === category) {
                    faq.style.display = 'block';
                } else {
                    faq.style.display = 'none';
                }
            });
        }
        
        // Add search functionality
        document.querySelector('input[placeholder="What do you want to know about brokers?"]').addEventListener('input', function(e) {
            const searchTerm = e.target.value.toLowerCase();
            const faqs = document.querySelectorAll('.faq-item');
            
            // Reset category to "All" when searching
            document.querySelectorAll('.cat-link').forEach(link => link.style.color = '#475569');
            document.querySelector('.cat-link').style.color = '#2563eb';
            
            faqs.forEach(faq => {
                const question = faq.querySelector('summary').textContent.toLowerCase();
                const answer = faq.querySelector('div').textContent.toLowerCase();
                
                if (question.includes(searchTerm) || answer.includes(searchTerm)) {
                    faq.style.display = 'block';
                } else {
                    faq.style.display = 'none';
                }
            });
        });
        </script>

